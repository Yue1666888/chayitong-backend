CREATE TABLE IF NOT EXISTS users (
    id BIGINT NOT NULL,
    business_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    display_name VARCHAR(48) NOT NULL,
    avatar_media_id BIGINT NULL,
    bio VARCHAR(100) NULL,
