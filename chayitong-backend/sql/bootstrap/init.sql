    CONSTRAINT chk_media_file_dimensions CHECK ((width IS NULL OR width > 0) AND (height IS NULL OR height > 0)),
    CONSTRAINT chk_media_file_duration CHECK (duration_ms IS NULL OR duration_ms BETWEEN 1 AND 60000),
    CONSTRAINT chk_media_file_status CHECK (status IN ('UPLOADED', 'BOUND', 'DELETED')),
    CONSTRAINT chk_media_file_binding CHECK ((bound_type IS NULL AND bound_id IS NULL) OR (bound_type IS NOT NULL AND bound_id IS NOT NULL)),
    CONSTRAINT chk_media_file_deleted CHECK (deleted IN (0, 1))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

